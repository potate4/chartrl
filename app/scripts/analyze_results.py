# ── Helpers ────────────────────────────────────────────────────────────────

def load_jsonl(path):
    samples = []
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            samples.append(json.loads(line))
    return samples


def bootstrap_ci(values, n_boot=N_BOOTSTRAP, ci=0.95):
    """Return (mean, lo, hi) for bootstrap CI."""
    arr = np.array(values, dtype=float)
    means = np.array([
        RNG.choice(arr, size=len(arr), replace=True).mean()
        for _ in range(n_boot)
    ])
    alpha = (1 - ci) / 2
    lo, hi = np.quantile(means, [alpha, 1 - alpha])
    return float(arr.mean()), float(lo), float(hi)


def pass_at_k(correct_matrix, k):
    """
    Compute Pass@K from a list of per-sample correct arrays.
    correct_matrix: list of lists of bool (n_samples x n_rollouts)
    Uses unbiased estimator: Pass@K = 1 - C(n-c, k) / C(n, k)
    """
    from math import comb
    scores = []
    for correct_list in correct_matrix:
        n = len(correct_list)
        c = sum(correct_list)
        if n < k:
            scores.append(1.0 if c > 0 else 0.0)
        elif c == 0:
            scores.append(0.0)
        elif n - c < k:
            # Not enough failures to fill k slots, so guaranteed at least 1 correct
            scores.append(1.0)
        else:
            scores.append(1.0 - comb(n - c, k) / comb(n, k))
    return np.mean(scores) * 100


def accuracy_histogram(values, bins=10):
    """Return histogram string."""
    counts, edges = np.histogram(values, bins=bins, range=(0, 1))
    lines = []
    for i, c in enumerate(counts):
        lo, hi = edges[i], edges[i + 1]
        bar = "#" * c
        lines.append(f"  [{lo:.1f}-{hi:.1f}) {c:4d} {bar}")
    return "\n".join(lines)


def reasoning_length(raw_output):
    """Count words in the <think> block."""
    if "<think>" in raw_output and "</think>" in raw_output:
        think = raw_output.split("<think>")[1].split("</think>")[0]
        return len(think.split())
    return len(raw_output.split())


